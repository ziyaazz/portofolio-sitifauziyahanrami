let currentLang = 'id';
let currentGallery = [];
let slideIndex = 0;

document.addEventListener('DOMContentLoaded', () => { renderProjects(); });

function switchLanguage(lang) {
    currentLang = lang;
    document.querySelectorAll('.lang-btn').forEach(btn => btn.classList.remove('active'));
    document.getElementById(`lang-${lang}`).classList.add('active');
    document.querySelectorAll('[data-i18n]').forEach(el => {
        const key = el.getAttribute('data-i18n');
        if (translations[lang] && translations[lang][key]) el.innerText = translations[lang][key];
    });
    renderProjects();
}

function renderProjects() {
    const grid = document.getElementById('projects-grid');
    if (!grid) return;
    grid.innerHTML = '';
    projectsData.forEach(proj => {
        const card = document.createElement('div');
        card.className = 'project-card';
        card.innerHTML = `
            <div class="project-cover-wrapper">
                <img src="${proj.cover}" alt="${proj.title[currentLang]}" class="project-cover" onerror="this.src='https://via.placeholder.com/400x250?text=Project+Image'">
            </div>
            <div class="project-content">
                <span class="tech-badge" style="width: fit-content; margin-bottom: 8px; background: var(--secondary-color); color: var(--primary-color); font-weight: 600;">${proj.category}</span>
                <h3 style="font-size: 1.15rem; margin-bottom: 8px;">${proj.title[currentLang] || proj.title['id']}</h3>
                <p style="font-size: 0.9rem; color: var(--text-muted); margin-bottom: 15px; flex-grow: 1;">${proj.shortDesc[currentLang] || proj.shortDesc['id']}</p>
                <button class="btn btn-primary" onclick="openModal('${proj.id}')">${translations[currentLang].btn_details}</button>
            </div>
        `;
        grid.appendChild(card);
    });
}

function openModal(id) {
    const proj = projectsData.find(p => p.id === id);
    if (!proj) return;
    
    currentGallery = proj.details.gallery || [];
    slideIndex = 0;
    
    let galleryHTML = '';
    if (currentGallery.length > 0) {
        galleryHTML = `
            <h4 style="margin-top: 15px; font-size: 1rem; color: var(--primary-color);">📸 Dokumentasi Foto:</h4>
            <div class="slider-container" style="position: relative; width: 100%; height: 230px; margin-top: 10px; overflow: hidden; border-radius: 8px; background: #222;">
                <img id="slider-img" src="${currentGallery[0].src}" style="width: 100%; height: 100%; object-fit: contain; transition: opacity 0.4s ease-in-out;" onerror="this.src='https://via.placeholder.com/400x230?text=Dokumentasi+Foto'">
                ${currentGallery.length > 1 ? `
                    <button onclick="nextSlide(-1)" style="position: absolute; left: 8px; top: 45%; background: rgba(0,0,0,0.6); color: white; border: none; padding: 8px 12px; cursor: pointer; border-radius: 50%; font-size: 1rem;">❮</button>
                    <button onclick="nextSlide(1)" style="position: absolute; right: 8px; top: 45%; background: rgba(0,0,0,0.6); color: white; border: none; padding: 8px 12px; cursor: pointer; border-radius: 50%; font-size: 1rem;">❯</button>
                ` : ''}
            </div>
        `;
    }

    const modalBody = document.getElementById('modal-body');
    modalBody.innerHTML = `
        <h2 style="font-size: 1.35rem; margin-bottom: 10px;">${proj.title[currentLang]}</h2>
        <div style="display: flex; flex-wrap: wrap; gap: 6px; margin-bottom: 15px;">
            ${proj.tech.map(t => `<span class="tag">${t}</span>`).join('')}
        </div>
        ${galleryHTML}
        <p style="margin-top: 15px; font-size: 0.95rem; color: var(--text-main);"><strong>Latar Belakang / Goal:</strong><br>${proj.details.bg[currentLang]}</p>
        <p style="margin-top: 15px; font-size: 0.95rem; color: var(--text-main);"><strong>Cara Kerja Sistem:</strong><br>${proj.details.howItWorks[currentLang]}</p>
    `;
    document.getElementById('project-modal').style.display = 'flex';
}

function closeModal() { document.getElementById('project-modal').style.display = 'none'; }

function nextSlide(step) {
    if (currentGallery.length <= 1) return;
    slideIndex += step;
    if (slideIndex < 0) slideIndex = currentGallery.length - 1;
    if (slideIndex >= currentGallery.length) slideIndex = 0;
    
    const sliderImg = document.getElementById('slider-img');
    if (sliderImg) {
        sliderImg.style.opacity = 0.2;
        setTimeout(() => {
            sliderImg.src = currentGallery[slideIndex].src;
            sliderImg.style.opacity = 1;
        }, 200);
    }
}